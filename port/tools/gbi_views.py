#!/usr/bin/env python3
"""Writes the port's views of a display-list command (sonarlib docs/porting-model.md, 64-bit and endianness).

The game reads a Gfx through bit-field structs laid out by the original compiler, which allocates a 32-bit word's
fields from its most significant bit. The host compilers allocate from the least significant bit, and a port's Gfx
keeps its second word in a 64-bit field so it can hold a host pointer. This script reads the console's structs
between `#include <port/NAME.h>` / `#else` and `#endif /* SONAR_PORT */` in each header below and writes
port/adapter/include/port/NAME.h, where each 32-bit word's fields are declared in reverse, each word fills the
8 bytes of its Gfx half, and an address takes the whole half. It also writes the test that checks each field's
position against the console's layout.

    python3 port/tools/gbi_views.py           write the views and the test
    python3 port/tools/gbi_views.py --check   exit 1 if any written file is out of date
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HEADERS = ["include/PR/gbi.h", "include/libforest/gbi_extensions.h"]
OUT_DIR = ROOT / "port/adapter/include/port"
TEST = ROOT / "port/tests/gbi_views_cases.inc"

# Fields that hold an address: the whole half, a host pointer in the port.
ADDRESSES = {
    ("Gdma", "addr"), ("Gsetimg", "dram"), ("Gsetimg2", "imgaddr"), ("Gloadtlut_dolphin", "tlut_addr"),
    ("Gmtx", "addr"), ("Gvtx", "addr"), ("Gmovemem", "data"), ("Gmoveword", "data"), ("Gnoop", "param1"),
}
SIGNED = {"int", "signed int", "short", "short int", "signed short", "s8", "s16", "s32", "char", "signed char"}
BITS = {"char": 8, "signed char": 8, "unsigned char": 8, "s8": 8, "u8": 8,
        "short": 16, "short int": 16, "signed short": 16, "unsigned short": 16, "s16": 16, "u16": 16,
        "int": 32, "signed int": 32, "unsigned int": 32, "unsigned long": 32, "long": 32, "s32": 32, "u32": 32,
        "Tri": 32}
PLAIN = {(8, False): "unsigned char", (8, True): "signed char", (16, False): "unsigned short", (16, True): "short",
         (32, False): "unsigned int", (32, True): "int"}
GENERATED = "/* Generated by port/tools/gbi_views.py from {src}; do not edit. */\n"


def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def parse_fields(body, name):
    """The struct's fields as (type, name, width or None) in declaration order."""
    fields = []
    for decl in strip_comments(body).split(";"):
        decl = " ".join(decl.split())
        if not decl:
            continue
        m = re.fullmatch(r"(.+?)\s+(\w+)\s*(?::\s*(\d+))?", decl)
        if not m:
            sys.exit(f"{name}: cannot read field '{decl}'")
        fields.append((m.group(1), m.group(2), int(m.group(3)) if m.group(3) else None))
    return fields


def layout(fields, name):
    """Each field's place on the console as (word, bit offset from the word's top, width)."""
    placed = []
    pos = 0  # bits from the start of the struct
    for ftype, fname, width in fields:
        if ftype not in BITS:
            sys.exit(f"{name}.{fname}: unknown type '{ftype}'")
        if width is None:
            width = BITS[ftype]
            align = min(width, 32)
            pos = (pos + align - 1) // align * align
        elif pos // 32 != (pos + width - 1) // 32:
            pos = (pos + 31) // 32 * 32
        placed.append((ftype, fname, pos // 32, pos % 32, width))
        pos += width
    words = (pos + 31) // 32
    return placed, words


def port_struct(tag, name, fields):
    placed, words = layout(fields, name)
    lines = [f"typedef struct {tag + ' ' if tag else ''}{{"]
    for word in range(words):
        in_word = [p for p in placed if p[2] == word]
        if len(in_word) == 1 and (name, in_word[0][1]) in ADDRESSES:
            lines.append(f"    uintptr_t {in_word[0][1]};")
            continue
        if all((f[0], f[1], None) in fields and f[0] != "Tri" for f in in_word):
            # Whole members only: declared in reverse as members, so their addresses can still be taken.
            for ftype, fname, _, offset, width in reversed(in_word):
                lines.append(f"    {PLAIN[(width, ftype in SIGNED)]} {fname};")
            lines.append("    unsigned int :32;")
            continue
        used = 0  # bits declared from the least significant up
        for ftype, fname, _, offset, width in reversed(in_word):
            low = 32 - offset - width
            if low > used:
                lines.append(f"    unsigned int :{low - used};")
            if ftype == "Tri":
                # The game reads only the command byte of a Gtri.
                lines.append(f"    unsigned int :32; /* {fname}: a Tri the game does not read */")
            else:
                kind = "signed int" if ftype in SIGNED else "unsigned int"
                lines.append(f"    {kind} {fname}:{width};")
            used = low + width
        if used < 32:
            lines.append(f"    unsigned int :{32 - used};")
        lines.append("    unsigned int :32;")
    lines.append(f"}} {name};")
    return "\n".join(lines), placed, words


def regions(path):
    text = (ROOT / path).read_text()
    for m in re.finditer(r"#include <port/(\w+)\.h>\n#else\n(.*?)#endif /\* SONAR_PORT \*/", text, re.S):
        yield m.group(1), m.group(2)


def generate():
    files = {}
    cases = []
    for header in HEADERS:
        for out_name, region in regions(header):
            parts = [GENERATED.format(src=header), f"#ifndef PORT_{out_name.upper()}_H",
                     f"#define PORT_{out_name.upper()}_H", "", "#include <stdint.h>", "",
                     "#if defined(__BYTE_ORDER__) && __BYTE_ORDER__ != __ORDER_LITTLE_ENDIAN__",
                     "#error \"The views are laid out for a little-endian host\"", "#endif", ""]
            code = strip_comments(region)
            item = re.compile(r"typedef\s+(struct|union)\s*(\w*)\s*\{(.*?)\}\s*(\w+)\s*;|typedef\s+(\w+)\s+(\w+)\s*;",
                              re.S)
            for m in item.finditer(code):
                if m.group(5):
                    parts.append(f"typedef {m.group(5)} {m.group(6)};\n")
                elif m.group(1) == "union":
                    members = "\n".join(f"    {' '.join(d.split())};" for d in m.group(3).split(";") if d.strip())
                    parts.append(f"typedef union {{\n{members}\n}} {m.group(4)};\n")
                else:
                    name = m.group(4)
                    struct, placed, words = port_struct(m.group(2), name, parse_fields(m.group(3), name))
                    parts.append(struct + "\n")
                    cases.append((name, placed, words))
            parts.append("#endif\n")
            files[OUT_DIR / f"{out_name}.h"] = "\n".join(parts)
    test = [GENERATED.format(src=", ".join(HEADERS)).rstrip(),
            "/* CHECK_SIZE(view, gfx count); CHECK_FIELD(view, field, word, mask in that word) */"]
    for name, placed, words in cases:
        test.append(f"CHECK_SIZE({name}, {(words + 1) // 2})")
        for ftype, fname, word, offset, width in placed:
            if ftype == "Tri":
                continue
            if (name, fname) in ADDRESSES:
                test.append(f"CHECK_FIELD({name}, {fname}, {word}, UINTPTR_MAX)")
            else:
                mask = ((1 << width) - 1) << (32 - offset - width)
                test.append(f"CHECK_FIELD({name}, {fname}, {word}, 0x{mask:08x}u)")
    files[TEST] = "\n".join(test) + "\n"
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if a written file is out of date")
    args = parser.parse_args()
    stale = []
    for path, text in generate().items():
        if path.exists() and path.read_text() == text:
            continue
        if args.check:
            stale.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("out of date: " + ", ".join(map(str, stale)) + "; run port/tools/gbi_views.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
